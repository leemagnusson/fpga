"""Vivado constraints for the FPGA design (../litefury_canfd, BOARD=artix_m2), read from the routed board so
the pins cannot drift from the copper.

    python3 gen/xdc.py            # write ../litefury_canfd/constraints/artix_m2_early.xdc and artix_m2.xdc
    python3 gen/xdc.py --check    # exit 1 if those files differ from what the board says

The PCIe lanes are reversed on the GTP quad (M.2 lane n on channel 3-n) and the transmit pairs are
polarity-swapped on the board; the first is the LOC of each lane's GTPE2_CHANNEL here, the second needs
nothing (the host corrects it in training), so the FPGA's txp port simply sits on its MGTPTXP ball."""
import os, re, sys
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(os.path.dirname(ROOT), "litefury_canfd", "constraints")
PKG = os.path.join(HERE, "data", "xc7a50tcsg325pkg.txt")


def ball_names():
    from design import load_fpga_balls
    return {b: n for b, n, bank in load_fpga_balls(PKG)}


def board_nets():
    board = pcbnew.LoadBoard(os.path.join(ROOT, "artix_m2_canfd.kicad_pcb"))
    fpga = max(board.GetFootprints(), key=lambda f: f.GetPadCount())
    return {p.GetNetname().lstrip("/"): p.GetNumber() for p in fpga.Pads()}


def generate():
    net, name = board_nets(), ball_names()
    by_name = {n: b for b, n in name.items()}
    early = ["# GENERATED by artix_m2_canfd/gen/xdc.py from the routed board: do not edit.",
             "# Processed before the PCIe IP's own constraints (PROCESSING_ORDER EARLY).",
             "# M.2 lane n is on GTP channel 3-n; the transmit pairs are polarity-swapped on the board,",
             "# which the host corrects in link training, so txp stays on the MGTPTXP ball."]
    pins = []
    for lane in range(4):
        rxp = net[f"PCIE_RX{lane}_P"]
        ch = int(re.match(r"MGTPRXP(\d)_216", name[rxp]).group(1))
        assert name[net[f"PCIE_RX{lane}_N"]] == f"MGTPRXN{ch}_216", lane
        # board nets are named for the M.2 side: on the swapped pairs PCIE_TXn_N is on the TXP ball
        txp, txn = by_name[f"MGTPTXP{ch}_216"], by_name[f"MGTPTXN{ch}_216"]
        assert {net[f"PCIE_TX{lane}_P"], net[f"PCIE_TX{lane}_N"]} == {txp, txn}, lane
        swapped = net[f"PCIE_TX{lane}_N"] == txp
        early.append(f"set_property LOC GTPE2_CHANNEL_X0Y{ch} [get_cells -hierarchical -regexp "
                     f"{{.*pipe_lane\\[{lane}\\]\\.gt_wrapper_i/gtp_channel\\.gtpe2_channel_i}}]")
        pins += [f"set_property PACKAGE_PIN {rxp:3s} [get_ports {{pcie_mgt_rxp[{lane}]}}]",
                 f"set_property PACKAGE_PIN {net[f'PCIE_RX{lane}_N']:3s} [get_ports {{pcie_mgt_rxn[{lane}]}}]",
                 f"set_property PACKAGE_PIN {txp:3s} [get_ports {{pcie_mgt_txp[{lane}]}}]"
                 + ("   ;# board: PERn (swapped)" if swapped else ""),
                 f"set_property PACKAGE_PIN {txn:3s} [get_ports {{pcie_mgt_txn[{lane}]}}]"]
    assert name[net["PCIE_REFCLK_P"]] == "MGTREFCLK0P_216"
    early += [""] + pins + ["", "# 100 MHz PCIe reference clock from the M.2 connector (MGTREFCLK0, not inverted)",
              f"set_property PACKAGE_PIN {net['PCIE_REFCLK_P']} [get_ports pcie_refclk_clk_p]",
              f"set_property PACKAGE_PIN {net['PCIE_REFCLK_N']} [get_ports pcie_refclk_clk_n]",
              "create_clock -period 10.000 -name pcie_refclk [get_ports pcie_refclk_clk_p]"]

    def io(n, port, extra=""):
        return f"set_property -dict {{PACKAGE_PIN {net[n]:3s} IOSTANDARD LVCMOS33{extra}}} [get_ports {port}]"
    late = ["# GENERATED by artix_m2_canfd/gen/xdc.py from the routed board: do not edit.",
            "# artix_m2_canfd card (XC7A50T-2CSG325I) pins. Processed after the IP constraints (PROCESSING_ORDER LATE).",
            "", "## 100 MHz oscillator on an MRCC pin (the block design creates the clock)",
            io("CLK100M", "sys_clk"),
            "", "## PCIe reset from the M.2 connector",
            io("PCIE_PERST_N", "pcie_perst_n"), "set_false_path -from [get_ports pcie_perst_n]",
            "", "## User LEDs (active low: 1k to 3.3 V)"]
    late += [io(f"LED{i}_N", f"{{leds[{i}]}}", " DRIVE 8") for i in range(4)]
    late += ["", "## CAN transceivers (MCP2542FD), one per CAN core. With CAN_CORES < 4 the design holds the",
             "## spare ones recessive and in standby; their RXD pins are then unused (pulled up, see UNUSEDPIN)."]
    for i in range(4):
        late += [io(f"CAN{i}_TXD", f"can{i}_tx", " DRIVE 8 SLEW FAST"),
                 io(f"CAN{i}_RXD", f"can{i}_rx", " PULLUP true"),
                 io(f"CAN{i}_STBY", f"can{i}_stby", " DRIVE 8")]
    late += ["set_false_path -to   [get_ports {can*_tx can*_stby leds[*]}]",
             "set_false_path -from [get_ports -quiet can*_rx]",
             "", "## Configuration: QSPI x4 from the W25Q128JV, internal config clock, compressed bitstream",
             "## (fast enough for PCIe to enumerate). Banks 0 and 14 are at 3.3 V.",
             "set_property BITSTREAM.CONFIG.OVERTEMPPOWERDOWN ENABLE [current_design]",
             "set_property BITSTREAM.CONFIG.CONFIGRATE 33 [current_design]",
             "set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]",
             "set_property CONFIG_MODE SPIx4 [current_design]",
             "set_property BITSTREAM.CONFIG.SPI_FALL_EDGE YES [current_design]",
             "set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]",
             "set_property BITSTREAM.CONFIG.UNUSEDPIN PULLUP [current_design]",
             "set_property CONFIG_VOLTAGE 3.3 [current_design]",
             "set_property CFGBVS VCCO [current_design]"]
    return {"artix_m2_early.xdc": "\n".join(early) + "\n", "artix_m2.xdc": "\n".join(late) + "\n"}


def main():
    sys.path.insert(0, HERE)
    files, bad = generate(), 0
    for fn, text in files.items():
        path = os.path.join(OUT, fn)
        if "--check" in sys.argv:
            if not os.path.exists(path) or open(path).read() != text:
                print(f"{path}: out of date, run python3 gen/xdc.py"); bad = 1
        else:
            open(path, "w").write(text); print("wrote", path)
    sys.exit(bad)


if __name__ == "__main__":
    main()
